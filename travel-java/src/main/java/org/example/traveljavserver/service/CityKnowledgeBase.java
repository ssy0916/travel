    /** 加载城市知识；未收录返回 null */
    public Knowledge load(String city) {
        if (city == null || city.isBlank()) {
            return null;
        }
        String normalized = normalize(city);
        Knowledge k = KNOWLEDGE.get(normalized);
        if (k == null) {
            return null;
        }
        return k;
    }

    /** 生成注入 prompt 的知识文本；k 为 null 时返回空串 */
    public String toPromptContext(Knowledge k) {
        if (k == null || k.content() == null || k.content().isBlank()) {
            return "";
        }
        return "\n【" + k.title() + "】\n" + k.content().strip() + "\n";
    }

    /** 去掉常见的“市”后缀以匹配知识库键 */
    private static String normalize(String city) {
        String c = city.trim();
        if (c.endsWith("市") && c.length() > 2) {
            return c.substring(0, c.length() - 1);
        }
        return c;
    }
